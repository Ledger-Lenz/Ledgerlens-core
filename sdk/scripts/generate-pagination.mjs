#!/usr/bin/env node
/**
 * Generates sdk/src/generated/pagination.ts (Zod schemas + types) from
 * proto/ledgerlens/v1/pagination.proto.
 *
 *   node scripts/generate-pagination.mjs          # write the file
 *   node scripts/generate-pagination.mjs --check  # exit 1 if it is out of date
 */
/* global console, process */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const protoPath = resolve(here, "../../proto/ledgerlens/v1/pagination.proto");
const outPath = resolve(here, "../src/generated/pagination.ts");

const SCALARS = {
  int32: "z.number().int()",
  int64: "z.number().int()",
  uint32: "z.number().int()",
  uint64: "z.number().int()",
  float: "z.number()",
  double: "z.number()",
  string: "z.string()",
  bool: "z.boolean()",
};
// Proto messages defined elsewhere, mapped to their hand-maintained Zod schemas.
const EXTERNAL = { RiskScoreProto: "RiskScoreSchema" };

const proto = readFileSync(protoPath, "utf8").replace(/\/\/.*$/gm, "");
const messages = [...proto.matchAll(/message\s+(\w+)\s*\{([^}]*)\}/g)].map(
  ([, name, body]) => ({
    name,
    fields: [
      ...body.matchAll(/(optional|repeated)?\s*(\w+)\s+(\w+)\s*=\s*\d+\s*;/g),
    ].map(([, label, type, field]) => ({ label, type, field })),
  }),
);
const local = new Set(messages.map((m) => m.name));

const zodType = (type) => {
  if (SCALARS[type]) return SCALARS[type];
  if (local.has(type)) return `${type}Schema`;
  if (EXTERNAL[type]) return EXTERNAL[type];
  throw new Error(`Unsupported proto type: ${type}`);
};

const externals = new Set();
const blocks = messages.map(({ name, fields }) => {
  const lines = fields.map(({ label, type, field }) => {
    if (EXTERNAL[type]) externals.add(EXTERNAL[type]);
    let expr = zodType(type);
    if (label === "repeated") expr = `z.array(${expr})`;
    if (label === "optional") expr += ".optional()";
    return `  ${field}: ${expr},`;
  });
  return [
    `export const ${name}Schema = z.object({`,
    ...lines,
    `});`,
    ``,
    `export type ${name} = z.infer<typeof ${name}Schema>;`,
  ].join("\n");
});

const output = [
  `// Code generated by scripts/generate-pagination.mjs from`,
  `// proto/ledgerlens/v1/pagination.proto. DO NOT EDIT.`,
  ``,
  `import { z } from "zod";`,
  ...(externals.size
    ? [`import { ${[...externals].sort().join(", ")} } from "../schemas";`]
    : []),
  ``,
  blocks.join("\n\n"),
  ``,
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // missing file counts as drift
  }
  if (current !== output) {
    console.error(
      "sdk/src/generated/pagination.ts is out of sync with proto/ledgerlens/v1/pagination.proto.",
    );
    console.error("Run `npm run generate` in sdk/ and commit the result.");
    process.exit(1);
  }
  console.log("Generated pagination types are up to date.");
} else {
  writeFileSync(outPath, output);
  console.log(`Wrote ${outPath}`);
}
